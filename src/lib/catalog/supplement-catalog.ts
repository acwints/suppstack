function slugify(value: string) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
}

function normalizeSupplementLookupTerm(value: string) {
  return value
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/\((.*?)\)/g, ' $1 ')
    .replace(/[^a-z0-9]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

