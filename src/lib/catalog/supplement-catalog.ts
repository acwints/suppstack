export const allCuratedProductSeeds: CuratedProductSeed[] = [
  ...curatedProductSeeds,
  ...sourcedProductSeeds,
];

function curatedSeedsForSupplementName(supplementName: string) {
  return allCuratedProductSeeds.filter(
    (product) => product.supplement_name.toLowerCase() === supplementName.toLowerCase()
  );
}

function curatedStatsForSupplementName(supplementName: string) {
  const products = curatedSeedsForSupplementName(supplementName);
  if (products.length === 0) return null;

  return {
    productCount: products.length,
    averagePrice: products.reduce((total, product) => total + product.product_price, 0) / products.length,
  };
}

function findCuratedSeedByProductId(productId: string) {
  return allCuratedProductSeeds.find((product) => product.product_id === productId) ?? null;
}

function createCuratedProduct(seed: CuratedProductSeed, supplement: Supplement): Product {
  return {
    ...seed,
    product_image: standardizeProductImage(seed.product_image),
    supplement_id: supplement.supplement_id,
    supplements: {
      supplement_id: supplement.supplement_id,
      supplement_name: supplement.supplement_name,
    },
  };
}

function createCuratedProductsForSupplement(supplement: Supplement): Product[] {
  return curatedSeedsForSupplementName(supplement.supplement_name).map((product) =>
    createCuratedProduct(product, supplement)
  );
}

/**
 * Real merchant product photography — every catalog supplement has at least
 * one curated product with a Shopify CDN image, so supplement tiles show an
 * actual product instead of stock category imagery.
 */
function productImageForSupplementName(supplementName: string) {
  const withImage = curatedSeedsForSupplementName(supplementName).find(
    (product) => product.product_image
  );
  return standardizeProductImage(withImage?.product_image);
}

export const supplementCatalog: Supplement[] = seeds.map((seed) => {
  const curatedStats = curatedStatsForSupplementName(seed.name);

  return {
    supplement_id: catalogIdForSeed(seed),
    supplement_name: seed.name,
    supplement_description: seed.description,
    image_url: productImageForSupplementName(seed.name),
    category: seed.category,
    aliases: seed.aliases,
    evidence_rating: seed.evidence,
    primary_goals: seed.goals,
    typical_forms: seed.forms,
    common_dosage: seed.dosage,
    // Honest numbers only: these come from real curated products. Every
    // catalog entry has at least one verified product, so no invented
    // fallbacks are needed.
    product_count: curatedStats?.productCount,
    average_price: curatedStats?.averagePrice,
  };
});

export function getCuratedCatalogProducts() {
  return allCuratedProductSeeds.flatMap((seed) => {
    const supplement = supplementCatalog.find(
      (item) => item.supplement_name.toLowerCase() === seed.supplement_name.toLowerCase()
    );

    return supplement ? [createCuratedProduct(seed, supplement)] : [];
  });
}


export function getCanonicalSupplementCategory(supplementName?: string | null) {
  if (!supplementName) return null;
  return (
    supplementCatalog.find(
      (supplement) => supplement.supplement_name.toLowerCase() === supplementName.toLowerCase()
    )?.category ?? null
  );
}

export function findCatalogSupplementById(id: number) {
  return supplementCatalog.find((supplement) => supplement.supplement_id === id);
}

export function findCatalogSupplementByName(name?: string | null) {
  if (!name) return null;
  const normalizedName = normalizeSupplementLookupTerm(name);

  return (
    supplementCatalog.find((supplement) => {
      const names = [supplement.supplement_name, ...(supplement.aliases ?? [])].map(
        normalizeSupplementLookupTerm
      );

      return names.some(
        (candidate) =>
          candidate === normalizedName ||
          candidate.endsWith(` ${normalizedName}`) ||
          normalizedName.endsWith(` ${candidate}`) ||
          normalizedName.includes(` ${candidate} `)
      );
    }) ?? null
  );
}

export function findCatalogSupplementForSupplement(supplement?: Supplement | null) {
  if (!supplement) return null;
  return findCatalogSupplementById(supplement.supplement_id) ?? findCatalogSupplementByName(supplement.supplement_name);
}

export function createCanonicalCatalogProductsForSupplement(supplement: Supplement) {
  const catalogSupplement = findCatalogSupplementForSupplement(supplement);
  if (!catalogSupplement) return createCatalogProductsForSupplement(supplement);

  return createCatalogProductsForSupplement({
    ...catalogSupplement,
    supplement_id: supplement.supplement_id,
  });
}

/**
 * Database products are only listed when they carry a verified commerce path
 * (a Shopify variant or direct checkout). Legacy seeded rows with stock
 * photography and unverified prices are excluded from all product surfaces.
 */
export function isListableDatabaseProduct(product: Product) {
  return hasShopifyVariant(product) || hasDirectShopifyCheckout(product);
}

export function resolveProductsForSupplement(
  supplement: Supplement,
  databaseProducts: Product[] = []
) {
  const catalogProducts = createCanonicalCatalogProductsForSupplement(supplement);
  const listableDatabaseProducts = databaseProducts
    .filter(isListableDatabaseProduct)
    .map((product) => ({
      ...product,
      product_image: standardizeProductImage(product.product_image),
    }));
  return mergeProductSources(catalogProducts, listableDatabaseProducts);
}

export function findCatalogSupplementByProductId(productId: string) {
  const curatedSeed = findCuratedSeedByProductId(productId);
  if (!curatedSeed) return null;

  return supplementCatalog.find((supplement) => supplement.supplement_name === curatedSeed.supplement_name) ?? null;
}

/**
 * Only real, verified merchant products are ever listed. There is no
 * generated/fallback product data — if a supplement has no curated products,
 * callers render an honest empty state instead.
 */
export function createCatalogProductsForSupplement(supplement: Supplement): Product[] {
  return createCuratedProductsForSupplement(supplement);
}

export function findCatalogProductById(productId: string) {
  const supplement = findCatalogSupplementByProductId(productId);
  if (!supplement) return null;

  return createCatalogProductsForSupplement(supplement).find((product) => product.product_id === productId) ?? null;
}
